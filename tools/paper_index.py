#!/usr/bin/env python3
"""Builds src/paperindex.js (the mix-and-match question map) from index-<subject>.json files.

  python3 tools/paper_index.py tools/paper-index

The map holds metadata only (year, question number, part label, marks, page, topic codes and a few
of our own words about each part). Nothing from the papers is copied.
"""
import json, os, sys

RULES = {'y12': (10, 90), 'e1': (10, 60), 'phys': (20, 80)}  # multiple choice items, Section II marks

def check(sid, idx):
    mc_n, sec2 = RULES[sid]
    for y, p in idx.items():
        assert len(p['mc']) == mc_n, f'{sid} {y}: {len(p["mc"])} MC'
        assert sum(q['marks'] for q in p['q']) == sec2, f'{sid} {y}: Section II marks'
        for q in p['q']:
            assert sum(x['marks'] for x in q['parts']) == q['marks'], f'{sid} {y} Q{q["n"]}: parts add up'
            for x in q['parts']:
                assert len(x.get('about', '').split()) <= 8, f'{sid} {y} Q{q["n"]}{x["label"]}: about is short'
    return idx

src = sys.argv[1] if len(sys.argv) > 1 else '.'
out = {}
for sid in RULES:
    f = os.path.join(src, f'index-{sid}.json')
    if os.path.exists(f): out[sid] = check(sid, json.load(open(f)))
# Older Ext 2 papers (old course): only the parts that fit the current course are listed.
for f in sorted(x for x in os.listdir(src) if x.startswith('index-y12-old-') and x.endswith('.json')):
    for y, p in json.load(open(os.path.join(src, f))).items():
        for q in p['q']:
            assert sum(x['marks'] for x in q['parts']) <= q['marks'], f'old {y} Q{q["n"]}: parts within marks'
        out.setdefault('y12', {})[y] = p
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
with open(os.path.join(root, 'src', 'paperindex.js'), 'w') as fh:
    fh.write('/* ===== Lock In — where every HSC past paper question is (generated by tools/paper_index.py) =====\n'
             '   Metadata only: year, question, part, marks, page and topics. The questions themselves stay on nsw.gov.au. */\n')
    fh.write('const PAPER_INDEX = ' + json.dumps(out, separators=(',', ':')) + ';\n')
    fh.write("if (typeof module !== 'undefined') module.exports = PAPER_INDEX;\n")
print({k: len(v) for k, v in out.items()})
