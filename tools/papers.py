#!/usr/bin/env python3
"""Builds src/papers.js from the PDFs in desktop/papers/ (named <subject>-<year>-paper.pdf / -mg.pdf).

The PDFs ship inside the desktop app only (desktop/papers/ is git-ignored, so they never go in the
public repo or website). The app opens them in its own viewer."""
import json, os, re
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
folder = os.path.join(root, 'desktop', 'papers')
CURRENT = {'y12': 2020, 'e1': 2020, 'phys': 2019}  # first year of the current course
L = {}
for f in sorted(os.listdir(folder)):
    m = re.match(r'(y12|e1|phys)-(\d{4})-(paper|mg)\.pdf$', f)
    if not m: continue
    sid, y, kind = m.group(1), int(m.group(2)), m.group(3)
    e = next((x for x in L.setdefault(sid, []) if x['year'] == y), None)
    if not e: e = {'year': y}; L[sid].append(e)
    e[kind] = 'papers/' + f
    if y < CURRENT[sid]: e['old'] = True
for sid in L: L[sid] = sorted([e for e in L[sid] if 'paper' in e], key=lambda e: -e['year'])
FORMAT = {
 'y12': {'name': 'Maths Extension 2', 'reading': 10, 'writing': 180, 'parts': [['I', 'Section I: multiple choice', 10]] + [[f'Q{q}', f'Question {q}', 15] for q in range(11, 17)]},
 'y12old': {'name': 'Maths Extension 2 (old course)', 'reading': 5, 'writing': 180, 'parts': [[f'Q{q}', f'Question {q}', 15] for q in range(1, 9)]},
 'e1': {'name': 'Maths Extension 1', 'reading': 10, 'writing': 120, 'parts': [['I', 'Section I: multiple choice', 10]] + [[f'Q{q}', f'Question {q}', 15] for q in range(11, 15)]},
 'phys': {'name': 'Physics', 'reading': 5, 'writing': 180, 'parts': [['I', 'Section I: multiple choice', 20], ['II', 'Section II: short answers and extended responses', 80]]},
}
js = f"""/* ===== Lock In — official HSC past papers (generated by tools/papers.py) =====
   The PDFs are bundled in the desktop app only (desktop/papers/, not in the public repo or website).
   FORMAT is each paper's structure for the timer and mark sheet. Ext 2 papers before 2012 had eight
   15-mark questions and no multiple choice ('y12old'). */
const PAPERS = (() => {{
  const LIST = {json.dumps(L)};
  const FORMAT = {json.dumps(FORMAT)};
  const formatOf = (sid, year) => (sid === 'y12' && year < 2012 ? FORMAT.y12old : FORMAT[sid]);
  const outOf = (sid, year) => formatOf(sid, year || 9999).parts.reduce((a, p) => a + p[2], 0);
  return {{ LIST, FORMAT, formatOf, outOf }};
}})();
if (typeof module !== 'undefined') module.exports = PAPERS;
"""
open(os.path.join(root, 'src', 'papers.js'), 'w').write(js)
print({k: len(v) for k, v in L.items()}, sum(1 for v in L.values() for e in v if e.get('old')), 'old')
